# ── paths 5 and 6: the arm's outline bands ────────────────────────────────────
#
# `python3 scripts/mascot/specs/thumbs_up.py` rewrites them in the SVG from the
# art's own paths 0-4 (anything after the rig-only comment is dropped first),
# then `build.py --check` must still say 0 px. Only run as a script: build.py
# loads this file for SPEC alone.
#
# Each band starts at the arm's edge and goes outward, as wide as the visible
# half of the outline (HALF) but never wider than the clearance the art leaves
# there at rest, less MARGIN, so it never touches other paper; its width changes
# by at most EASE per unit along the edge, so it has no steps, and tapers to
# nothing at both ends.
if __name__ == '__main__':
    import math, os, sys
    ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..')
    sys.path.insert(0, os.path.join(ROOT, 'scripts', 'mascot'))
    import kit

    SVG = os.path.join(ROOT, SPEC['svg'])
    MARKER = '<!-- rig-only:'
    HALF = 30       # the visible half of the 64-unit outline (32), less 2 so its edge never meets the stroke's
    MARGIN = 1.5    # kept clear of any paper at rest
    EASE = 0.3      # the most the width may change per unit along the edge
    STEP = 2.5      # sample spacing along the edge
    SIMPLIFY = 0.2  # how far a simplified edge may stray from the sampled one
    GAP = 0.6       # the band starts this far off the arm's edge, so the two never share an antialiased edge
    ARC = (82, 101)  # the arm on outline sub 0
    BANDS = [
        (82, 86),   # path 5: the forearm's underside and the heel of the hand, over petal lowerLeft
        (94, 101),  # path 6: the thumb's inner side and the forearm's top, under petal left
    ]

    src = open(SVG).read()
    if MARKER in src:
        src = src[:src.index(MARKER)] + src[src.rindex('</svg>'):]
    art = SVG + '.art.tmp'
    open(art, 'w').write(src)
    paths = kit.parse_svg(art)
    os.remove(art)
    s0 = paths[0]['subs'][0]

    def fine(a, b, n=32):
        """the outline from anchor a to b, its curves cut into n pieces each"""
        A = kit.anchors(s0); pts = [A[a]]; i = a; x0, y0 = A[a]; M = len(s0['segs'])
        while i != b:
            k, seg = s0['segs'][i]
            if k == 'L': pts.append(tuple(seg))
            else:
                for j in range(1, n + 1):
                    t = j / n; mt = 1 - t
                    pts.append((mt ** 3 * x0 + 3 * mt * mt * t * seg[0] + 3 * mt * t * t * seg[2] + t ** 3 * seg[4],
                                mt ** 3 * y0 + 3 * mt * mt * t * seg[1] + 3 * mt * t * t * seg[3] + t ** 3 * seg[5]))
            x0, y0 = pts[-1]; i = (i + 1) % M
        return pts

    def resample(pts, step):
        out = [pts[0]]; need = step
        for a, b in zip(pts, pts[1:]):
            L = math.hypot(b[0] - a[0], b[1] - a[1]); pos = 0.0
            while L - pos >= need:
                pos += need; need = step
                out.append((a[0] + (b[0] - a[0]) * pos / L, a[1] + (b[1] - a[1]) * pos / L))
            need -= L - pos
        if math.hypot(out[-1][0] - pts[-1][0], out[-1][1] - pts[-1][1]) > step * 0.3: out.append(pts[-1])
        return out

    # what a band must keep clear of at rest: the rest of the outline, its holes, the fingers, the marks
    obstacles = []
    def add(poly, closed=True):
        for a, b in zip(poly, poly[1:] + ([poly[0]] if closed else [])): obstacles.append((a, b))
    add(fine(ARC[1], ARC[0]), closed=False)
    for sp in paths[0]['subs'][1:]: add(kit.flat(sp, 24))
    for pth in paths[1:]:
        if pth['opacity'] < 0.5 or pth['fill'] == 'rgb(3,3,3)': continue
        for sp in pth['subs']: add(kit.flat(sp, 24))
    outer = kit.flat(s0, 24)

    def segdist(p, a, b):
        dx, dy = b[0] - a[0], b[1] - a[1]; L = dx * dx + dy * dy or 1e-12
        t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L))
        return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)

    def orient(p, q, r): return (q[0] - p[0]) * (r[1] - p[1]) - (q[1] - p[1]) * (r[0] - p[0])

    def unfold(line):
        """cut the loops an offset line makes where the edge it follows turns inward"""
        changed = True
        while changed:
            changed = False
            for i in range(len(line) - 1):
                for j in range(len(line) - 2, i + 1, -1):
                    A, B, C, D = line[i], line[i + 1], line[j], line[j + 1]
                    d1, d2, d3, d4 = orient(A, B, C), orient(A, B, D), orient(C, D, A), orient(C, D, B)
                    if d1 * d2 < 0 and d3 * d4 < 0:
                        t = d3 / (d3 - d4)
                        line = line[:i + 1] + [(A[0] + (B[0] - A[0]) * t, A[1] + (B[1] - A[1]) * t)] + line[j + 1:]
                        changed = True; break
                if changed: break
        return line

    def dp(pts, eps):
        """Douglas-Peucker"""
        if len(pts) < 3: return list(pts)
        a, b = pts[0], pts[-1]; dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy) or 1e-9
        i, dmax = 0, -1.0
        for k in range(1, len(pts) - 1):
            d = abs((pts[k][0] - a[0]) * dy - (pts[k][1] - a[1]) * dx) / L
            if d > dmax: i, dmax = k, d
        if dmax <= eps: return [a, b]
        return dp(pts[:i + 1], eps)[:-1] + dp(pts[i:], eps)

    def band(a, b):
        pts = resample(fine(a, b), STEP); n = len(pts)
        normals = []
        for i in range(n):
            p0, p1 = pts[max(i - 1, 0)], pts[min(i + 1, n - 1)]
            tx, ty = p1[0] - p0[0], p1[1] - p0[1]; L = math.hypot(tx, ty) or 1
            nx, ny = ty / L, -tx / L
            if kit.inside((pts[i][0] + 3 * nx, pts[i][1] + 3 * ny), outer): nx, ny = -nx, -ny
            normals.append((nx, ny))
        clear = [min(HALF, min(segdist(p, *o) for o in obstacles) - MARGIN) for p in pts]
        clear[0] = clear[-1] = 0
        s = [0.0]
        for p, q in zip(pts, pts[1:]): s.append(s[-1] + math.hypot(q[0] - p[0], q[1] - p[1]))
        w = [max(0.0, min(clear[j] + EASE * abs(s[i] - s[j]) for j in range(n))) for i in range(n)]
        keep = [i for i in range(n) if w[i] > GAP + 0.3]
        lo, hi = keep[0], keep[-1]
        off = lambda i, d: (pts[i][0] + d * normals[i][0], pts[i][1] + d * normals[i][1])
        inner = unfold([off(i, GAP) for i in range(lo, hi + 1)])
        edge = unfold([off(i, max(GAP, w[i])) for i in range(lo, hi + 1)])
        return dp(inner, SIMPLIFY) + dp(edge, SIMPLIFY)[::-1]

    f = lambda v: ('%.1f' % v).rstrip('0').rstrip('.')
    out = MARKER + " the two shapes below are the arm's outline where it meets petals left and lowerLeft, filled in the gap colour, so the art is unchanged. See scripts/mascot/specs/thumbs_up.py. -->\n"
    for a, b in BANDS:
        out += '<path transform="translate(0,0)" fill="rgb(3,3,3)" d="M%sZ"/>\n' % ' L'.join('%s %s' % (f(x), f(y)) for x, y in band(a, b))
    i = src.rindex('</svg>')
    open(SVG, 'w').write(src[:i] + out + src[i:])
    print('wrote the arm bands (paths 5, 6) into', os.path.relpath(SVG, ROOT))
