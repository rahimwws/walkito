/** A site path or full URL, as a path. */
const pathOf = (u: string) => u.replace(/^https?:\/\/[^/]+/, '');

/** Out of Google's index: hidden from Google, or merged into another page. */
export function isGoogleHidden(pathOrUrl: string): boolean {
  const p = pathOf(pathOrUrl);
  return GOOGLE_HIDDEN.has(p) || p in MERGED;
}

export function mergedTarget(pathOrUrl: string): string | undefined {
  return MERGED[pathOf(pathOrUrl)];
}
