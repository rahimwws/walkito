/**
 * The scene-based life cycle, which the iOS 27 SDK requires.
 *
 * An app linked against the iOS 27 SDK that still runs the old app-delegate
 * window life cycle is stopped by UIKit at launch, in
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`
 * (EXC_BREAKPOINT, before any JavaScript runs). Xcode 27 builds hit it on the
 * iOS 27 simulator; EAS builds made with Xcode 26 do not yet, but will the day
 * EAS moves to Xcode 27.
 *
 * Expo 57.0.24 already ships the native half (`ExpoAppSceneDelegate`,
 * `SceneEventForwarder`, `ExpoReactNativeFactoryProvider` in
 * node_modules/expo/ios/AppDelegates); the SDK 57 bare template just does not
 * use it yet. This plugin applies what the SDK 58 template does
 * (expo-template-bare-minimum@58.0.16):
 *
 * - **AppDelegate** conforms to `ExpoReactNativeFactoryProvider` and no longer
 *   creates the window or starts React Native in `didFinishLaunching`. The
 *   factory is still made there; the scene delegate starts it.
 * - **SceneDelegate.swift**, a subclass of `ExpoAppSceneDelegate`, creates the
 *   window from the connecting scene, mirrors it onto the app delegate, starts
 *   React Native with launch options rebuilt from the scene's connection
 *   options (so `Linking.getInitialURL()` still sees a cold-start link), and
 *   forwards URL, user-activity, life-cycle and quick-action events back to
 *   the app delegate.
 * - **Info.plist** gets `UIApplicationSceneManifest`, one window scene.
 *
 * A quick action that cold-starts the app is handed to expo-quick-actions
 * from the scene's connection options (see WITH_QUICK_ACTIONS below).
 *
 * Unlike the SDK 58 template, the open-URL and continue-user-activity
 * overrides stay in AppDelegate: react-native-appsflyer's plugin writes its
 * `AppsFlyerAttribution` calls into them, and `SceneEventForwarder` reaches
 * them by dynamic dispatch through `ExpoAppDelegate`. It also notifies
 * `RCTLinkingManager` only when the override did not, so a link is not
 * delivered to JavaScript twice.
 *
 * Fails the prebuild if the AppDelegate no longer looks like the template it
 * edits: half of this change is worse than none (two windows, or none).
 * Remove the plugin when Expo's own template does all of it (SDK 58).
 */
const fs = require('fs');
const path = require('path');
const { IOSConfig, withInfoPlist, withAppDelegate, withXcodeProject } = require('expo/config-plugins');

const MARKER = '// walkito: window and React Native start in SceneDelegate (plugins/with-scene-delegate.js)';
const FILE = 'SceneDelegate.swift';

const HEADER = `// Generated by plugins/with-scene-delegate.js. The window is created and React
// Native is started here, under the scene-based life cycle the iOS 27 SDK
// requires. See ExpoAppSceneDelegate in node_modules/expo/ios/AppDelegates.`;

const PLAIN = `internal import Expo

${HEADER}
@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  // Extension point for config plugins.
}
`;

/**
 * With expo-quick-actions: a quick action that cold-starts the app arrives in
 * the scene's connection options, not in launchOptions, and expo-quick-actions
 * (6.0.2) only reads launchOptions. Expo forwards it as a notification posted
 * before any JS listens, so without this the "SOMETHING OFF?" item, and the
 * dynamic one, would open the app and do nothing. Hand it to the module's own
 * app-delegate subscriber first, the way didFinishLaunching would have, so
 * `QuickActions.initial` is set before JS reads it.
 */
const WITH_QUICK_ACTIONS = `internal import Expo
internal import ExpoModulesCore
internal import ExpoQuickActions

${HEADER}
@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  override func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    if let item = connectionOptions.shortcutItem {
      _ = ExpoAppDelegateSubscriberRepository.getSubscriberOfType(ExpoQuickActionsAppDelegate.self)?
        .application(UIApplication.shared, didFinishLaunchingWithOptions: [.shortcutItem: item])
    }
    super.scene(scene, willConnectTo: session, options: connectionOptions)
  }
}
`;

/** Only when the package is installed, so removing it cannot break the build. */
function sceneDelegateSource(projectRoot) {
  const pkg = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8'));
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  return deps['expo-quick-actions'] != null ? WITH_QUICK_ACTIONS : PLAIN;
}

/** The window block the SDK 57 template writes into didFinishLaunching. */
const WINDOW_BLOCK =
  /#if os\(iOS\) \|\| os\(tvOS\)\s*\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)\s*\n\s*factory\.startReactNative\([\s\S]*?\)\s*\n#endif\s*\n/;

function editAppDelegate(contents) {
  if (contents.includes(MARKER)) return contents;

  const declaration = /class AppDelegate: ExpoAppDelegate(\s*,[^{]*)?\s*\{/;
  const found = contents.match(declaration);
  if (found == null) {
    throw new Error('[with-scene-delegate] AppDelegate.swift: `class AppDelegate: ExpoAppDelegate` not found.');
  }
  if (!found[0].includes('ExpoReactNativeFactoryProvider')) {
    contents = contents.replace(found[0], found[0].replace(/\s*\{$/, ', ExpoReactNativeFactoryProvider {'));
  }

  if (!WINDOW_BLOCK.test(contents)) {
    throw new Error(
      '[with-scene-delegate] AppDelegate.swift: the template window block (UIWindow + startReactNative) was not found. ' +
        'Check what generated the AppDelegate before changing this plugin.',
    );
  }
  return contents.replace(WINDOW_BLOCK, `    ${MARKER}\n`);
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (config) => {
    if (config.modResults.language !== 'swift') {
      throw new Error(`[with-scene-delegate] expected a Swift AppDelegate, got ${config.modResults.language}.`);
    }
    config.modResults.contents = editAppDelegate(config.modResults.contents);
    return config;
  });
}

function withSceneManifest(config) {
  return withInfoPlist(config, (config) => {
    config.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: 'Default Configuration',
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return config;
  });
}

function withSceneDelegateFile(config) {
  return withXcodeProject(config, (config) => {
    const project = config.modResults;
    const projectName = IOSConfig.XcodeUtils.getProjectName(config.modRequest.projectRoot);
    const source = path.join(config.modRequest.platformProjectRoot, projectName, FILE);
    fs.writeFileSync(source, sceneDelegateSource(config.modRequest.projectRoot));

    const filepath = `${projectName}/${FILE}`;
    if (!project.hasFile(filepath)) {
      const { uuid: targetUuid } = IOSConfig.XcodeUtils.getApplicationNativeTarget({ project, projectName });
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project, targetUuid });
    }
    return config;
  });
}

module.exports = function withSceneDelegate(config) {
  config = withSceneAppDelegate(config);
  config = withSceneManifest(config);
  config = withSceneDelegateFile(config);
  return config;
};
